// End-to-end HTTP checks using disposable repositories, never the user's project.
import { execFileSync } from 'node:child_process'
import { existsSync, mkdtempSync, mkdirSync, writeFileSync, readFileSync, rmSync } from 'node:fs'
import { resolve, join, sep } from 'node:path'
import assert from 'node:assert/strict'
import { startServer, defaultExecutable } from './server.mjs'
const workspace = resolve('work')
mkdirSync(workspace, { recursive: true })
const fixture = mkdtempSync(join(workspace, 'smoke-'))
const repo = join(fixture, 'project')
mkdirSync(repo)
const git = (...args) => execFileSync('git', ['-C', repo, ...args], { encoding: 'utf8', windowsHide: true, stdio: ['ignore', 'pipe', 'pipe'] })
git('init', '-b', 'main')
git('config', 'user.name', 'gitowl Test')
git('config', 'user.email', 'gitowl@example.invalid')
git('config', 'commit.gpgsign', 'false')
git('config', 'core.autocrlf', 'false')
writeFileSync(join(repo, 'one.txt'), 'first\n')
writeFileSync(join(repo, 'later.txt'), 'later\n')
const executable = process.argv[2] && !process.argv[2].startsWith('--') ? resolve(process.argv[2]) : defaultExecutable
const nested = join(repo, 'nested')
mkdirSync(nested)
const outside = process.argv.includes('--outside')
const server = await startServer(executable, outside ? fixture : nested, { GIT_CEILING_DIRECTORIES: workspace, LOCALAPPDATA: fixture, XDG_CONFIG_HOME: fixture, HOME: fixture, USERPROFILE: fixture })
const { origin, request } = server
try {
  const bootResponse = await request({ op: 'bootstrap' })
  const boot = await bootResponse.json()
  if (outside) {
    assert.equal(boot.repo, null)
    const invalid = await request({ op: 'open', path: fixture })
    assert.equal(invalid.status, 400)
    const opened = await request({ op: 'open', path: nested })
    assert.equal(opened.status, 200)
    boot.repo = (await opened.json()).path
  }
  assert.equal(boot.repo.toLowerCase(), repo.toLowerCase())
  const call = async (op, data = {}) => {
    const response = await request({ op, repo: boot.repo, ...data })
    const value = await response.json()
    assert.equal(response.status, 200, JSON.stringify(value))
    return value
  }
  assert.equal((await request({ op: 'bootstrap' }, { 'x-gitowl-token': 'invalid' })).status, 403)
  assert.equal((await request({ op: 'bootstrap' }, { Origin: 'https://untrusted.invalid' })).status, 403)
  const html = await fetch(origin)
  assert.equal(html.status, 200)
  assert.ok(html.headers.get('content-security-policy').includes("frame-ancestors 'none'"))
  assert.match(await html.text(), /gitowl/)
  const state = await call('status')
  assert.equal(state.files.length, 2)
  await call('stage_all')
  const allStaged = await call('status')
  assert.equal(allStaged.files.every(f => f.staged), true)
  await call('unstage_all')
  const allUnstaged = await call('status')
  assert.equal(allUnstaged.files.every(f => !f.staged), true)
  await call('stage', { file: 'one.txt' })
  const staged = await call('status')
  assert.equal(staged.files.find(f => f.path === 'one.txt').staged, true)
  await call('commit', { message: 'First selected commit', fingerprint: staged.fingerprint })
  assert.equal(git('show', 'HEAD:one.txt').trim(), 'first')
  assert.throws(() => git('show', 'HEAD:later.txt'))
  writeFileSync(join(repo, 'one.txt'), 'changed\n')
  await call('discard', { file: 'one.txt' })
  assert.equal(readFileSync(join(repo, 'one.txt'), 'utf8'), 'first\n')
  writeFileSync(join(repo, 'one.txt'), 'stashed\n')
  writeFileSync(join(repo, 'stash-untracked.txt'), 'later\n')
  await call('stash_save', { message: 'Smoke stash', includeUntracked: true })
  assert.equal(readFileSync(join(repo, 'one.txt'), 'utf8'), 'first\n')
  assert.equal(existsSync(join(repo, 'stash-untracked.txt')), false)
  const stashList = await call('stash_list')
  assert.equal(stashList.stashes.length, 1)
  assert.match(stashList.stashes[0].message, /Smoke stash/)
  await call('stash_pop', { index: 0 })
  assert.equal(readFileSync(join(repo, 'one.txt'), 'utf8'), 'stashed\n')
  assert.equal(existsSync(join(repo, 'stash-untracked.txt')), true)
  await call('discard', { file: 'one.txt' })
  await call('discard', { file: 'stash-untracked.txt' })
  const history = await call('history', { query: 'selected' })
  assert.equal(history.commits.length, 1)
  assert.match((await call('commit_diff', { id: history.commits[0].id })).text, /first/)
  await call('create_branch', { branch: 'feature/check' })
  assert.equal((await call('status')).branch, 'feature/check')
  await call('branch_rename', { branch: 'feature/check', newName: 'feature/renamed' })
  assert.equal((await call('status')).branch, 'feature/renamed')
  await call('switch', { branch: 'main' })
  await call('branch_delete', { branch: 'feature/renamed' })
  assert.equal((await call('status')).branches.includes('feature/renamed'), false)
  await call('tag', { tag: 'v0.1-test' })
  await call('tag', { tag: 'v0.2-test', message: 'Smoke annotation' })
  assert.equal(git('tag').trim(), 'v0.1-test\nv0.2-test')
  assert.equal(git('cat-file', '-t', 'refs/tags/v0.2-test').trim(), 'tag')
  await call('tag_delete', { tag: 'v0.2-test' })
  assert.equal(git('tag').trim(), 'v0.1-test')
  const ignored = await call('ignore_read')
  await call('ignore_save', { previous: ignored.text, content: '*.log\n' })
  assert.equal(readFileSync(join(repo, '.gitignore'), 'utf8'), '*.log\n')
  const stale = await request({ op: 'ignore_save', repo: boot.repo, previous: 'stale', content: 'bad' })
  assert.equal(stale.status, 400)
  const remotePath = join(fixture, 'remote.git')
  execFileSync('git', ['init', '--bare', '-b', 'main', remotePath], { windowsHide: true, stdio: 'pipe' })
  await call('remote_add', { name: 'origin', url: remotePath })
  await call('remote_add', { name: 'backup', url: remotePath })
  await call('remote_set_url', { name: 'backup', url: remotePath })
  await call('remote_remove', { name: 'backup' })
  assert.deepEqual((await call('status')).remoteNames, ['origin'])
  const invalidPublish = await request({ op: 'publish', repo: boot.repo, remote: 'origin', branch: 'stale-branch' })
  assert.equal(invalidPublish.status, 400)
  await call('publish', { remote: 'origin', branch: 'main' })
  assert.equal((await call('status')).upstream, 'origin/main')
  await call('tag_push', { remote: 'origin', tag: 'v0.1-test' })
  assert.equal(execFileSync('git', ['-C', remotePath, 'tag', '--list'], { encoding: 'utf8' }).trim(), 'v0.1-test')
  const clonePath = join(fixture, 'clone')
  execFileSync('git', ['clone', remotePath, clonePath], { windowsHide: true, stdio: 'pipe' })
  const cloneGit = (...args) => execFileSync('git', ['-C', clonePath, ...args], { encoding: 'utf8', windowsHide: true, stdio: ['ignore', 'pipe', 'pipe'] })
  cloneGit('config', 'user.name', 'gitowl Test')
  cloneGit('config', 'user.email', 'gitowl@example.invalid')
  cloneGit('config', 'core.autocrlf', 'false')
  cloneGit('config', 'commit.gpgsign', 'false')
  writeFileSync(join(clonePath, 'pulled.txt'), 'remote\n')
  cloneGit('add', 'pulled.txt')
  cloneGit('commit', '-m', 'Remote pull source')
  cloneGit('push', 'origin', 'main')
  await call('pull', { mode: 'ff' })
  assert.equal(readFileSync(join(repo, 'pulled.txt'), 'utf8'), 'remote\n')
  const invalidPull = await request({ op: 'pull', repo: boot.repo, mode: 'squash' })
  assert.equal(invalidPull.status, 400)
  git('push', 'origin', 'HEAD:refs/heads/feature/shared')
  await call('fetch')
  const branches = await call('branches')
  assert.ok(branches.remote.some(b => b.name === 'origin/feature/shared'))
  assert.ok(branches.tags.includes('v0.1-test'))
  await call('checkout_remote', { reference: 'refs/remotes/origin/feature/shared', branch: 'feature/local' })
  assert.equal((await call('status')).upstream, 'origin/feature/shared')
  const metadataRepo = join(fixture, 'commit metadata')
  mkdirSync(metadataRepo)
  const metadataGit = (...args) => execFileSync('git', ['-C', metadataRepo, ...args], { encoding: 'utf8', windowsHide: true, stdio: 'pipe' })
  metadataGit('init', '-b', 'main')
  metadataGit('config', 'user.name', 'Before Author')
  metadataGit('config', 'user.email', 'before@example.invalid')
  metadataGit('config', 'commit.gpgsign', 'false')
  metadataGit('commit', '--allow-empty', '-m', 'Before message')
  boot.repo = (await call('open', { path: metadataRepo })).path
  const metadataPreview = await call('commit_edit_preview')
  assert.deepEqual(metadataPreview.blocked, [])
  const edited = await call('commit_edit', { ...metadataPreview, message: 'After message', authorName: 'After Author', authorEmail: 'after@example.invalid' })
  assert.equal(metadataGit('show', '-s', '--format=%s').trim(), 'After message')
  assert.equal(metadataGit('show', '-s', '--format=%an').trim(), 'After Author')
  const staleEdit = await request({ op: 'commit_edit', repo: boot.repo, ...metadataPreview })
  assert.equal(staleEdit.status, 400)
  await call('commit_edit_restore', edited)
  assert.equal(metadataGit('rev-parse', 'HEAD').trim(), metadataPreview.head)
  writeFileSync(join(metadataRepo, 'uncommitted.txt'), 'keep this')
  assert.ok((await call('commit_edit_preview')).blocked.length > 0)
  boot.repo = (await call('open', { path: repo })).path
  // Phase B: hunk staging, comparison, older-commit rewrite, rebase plan, recovery points, recent projects.
  const lines = Array.from({ length: 30 }, (_, i) => `line ${i + 1}`)
  writeFileSync(join(repo, 'hunks.txt'), lines.join('\n') + '\n')
  git('add', 'hunks.txt')
  git('commit', '-m', 'Add hunks file')
  lines[1] = 'line two'
  lines[27] = 'line twenty-eight'
  writeFileSync(join(repo, 'hunks.txt'), lines.join('\n') + '\n')
  const working = await call('diff', { file: 'hunks.txt', mode: 'working' })
  await call('hunk', { file: 'hunks.txt', mode: 'working', index: 0, previous: working.text })
  const stagedHunk = git('diff', '--cached')
  assert.match(stagedHunk, /\+line two/)
  assert.doesNotMatch(stagedHunk, /twenty-eight/)
  assert.equal((await request({ op: 'hunk', repo: boot.repo, file: 'hunks.txt', mode: 'working', index: 0, previous: working.text })).status, 400)
  git('commit', '-m', 'Partial hunk commit')
  git('checkout', '--', 'hunks.txt')
  const compared = await call('compare', { base: 'main', target: 'feature/local' })
  assert.equal(typeof compared.ahead, 'number')
  const rewriteRepo = join(fixture, 'rewrite')
  mkdirSync(rewriteRepo)
  const rewriteGit = (...args) => execFileSync('git', ['-C', rewriteRepo, ...args], { encoding: 'utf8', windowsHide: true, stdio: 'pipe' })
  rewriteGit('init', '-b', 'main')
  rewriteGit('config', 'user.name', 'Rewrite Test')
  rewriteGit('config', 'user.email', 'rewrite@example.invalid')
  rewriteGit('config', 'commit.gpgsign', 'false')
  for (const name of ['a', 'b', 'c']) rewriteGit('commit', '--allow-empty', '-m', `Commit ${name}`)
  boot.repo = (await call('open', { path: rewriteRepo })).path
  const target = rewriteGit('rev-parse', 'HEAD~1').trim()
  const rewritePreview = await call('rewrite_preview', { target })
  assert.equal(rewritePreview.commits.length, 2)
  await call('rewrite_edit', { ...rewritePreview, message: 'Commit b reworded', committerName: 'Fixed Committer' })
  assert.equal(rewriteGit('log', '-1', '--skip=1', '--format=%s|%cn').trim(), 'Commit b reworded|Fixed Committer')
  const planPreview = await call('rewrite_preview', { target: rewriteGit('rev-parse', 'HEAD~1').trim() })
  await call('rewrite_plan', { ...planPreview, steps: [{ id: planPreview.commits[1].id, action: 'pick' }, { id: planPreview.commits[0].id, action: 'drop' }] })
  assert.equal(rewriteGit('log', '--format=%s').trim(), 'Commit c\nCommit a')
  const points = await call('recovery_list')
  assert.equal(points.points.length, 2)
  await call('recovery_branch', { reference: points.points[0].ref, branch: 'recovered' })
  assert.match(rewriteGit('branch'), /recovered/)
  assert.ok((await call('bootstrap')).recent.length >= 2)
  boot.repo = (await call('open', { path: repo })).path
  const browse = await call('browse', { path: fixture })
  assert.ok(browse.directories.some(d => d.name === 'project'))
  const opened = await call('open', { path: repo })
  assert.equal(opened.path.toLowerCase(), repo.toLowerCase())
  console.log('PASS: startup, session protection, assets, file actions, stash, commits, history, branch rename/delete, remotes, publish/pull/tracking, commit metadata, tags and tag push, gitignore, hunks, compare, history rewrite, rebase plan, recovery points, recent projects, folder browsing and opening')
} finally {
  await server.stop()
  // Only remove the temporary directory created by this test beneath work/.
  if (!resolve(fixture).startsWith(workspace + sep)) throw new Error('Invalid cleanup path')
  rmSync(fixture, { recursive: true, force: true })
}
